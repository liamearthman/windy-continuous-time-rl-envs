"""
Synthetic data generation for windy cart-pole parameter recovery.

Rolls the forward model of `dynamics.py` forward under a known input and a
recorded noise path, then applies an observation model.  Three things here are
deliberate and matter later:

THE NOISE PATH IS STORED.  `Trajectory.dW` holds the exact increments used, not
a seed.  Any pathwise gradient method -- adjoint, autodiff through the solver,
forward sensitivities -- must differentiate the map at a FIXED noise
realization, so the realization has to be an input to the forward model rather
than a consequence of RNG state.  Storing it also means a loaded dataset can be
re-simulated bit-identically at different parameters, which is what a gradient
check needs.

NO TERMINATION.  The env stops an episode when |theta| > 12 deg or |x| > 2.4,
because it is an RL task.  Nothing here terminates: a trajectory that swings
far past upright is excellent identification data, since the nonlinearity in
sin(theta) and the Coriolis term is exactly what separates alpha from gamma.
The consequence is that these trajectories are NOT in the state distribution
the RL agents are trained on; do not reuse them as RL rollouts.

MOMENTA, NOT VELOCITIES.  The state is (x, theta, p_x, p_theta) and the mass
matrix couples the two velocities, so p is not a scaled velocity.  Use
`initial_state` to build z0 from the velocities you actually have in mind --
setting p_theta when you meant thetadot is a silent factor-of-32 error here.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Optional, Sequence

import numpy as np

from . import dynamics as dyn
from .dynamics import PARAM_NAMES, Params

# The env's force limit; the integrator clips to this before using u, so data
# generated without the same clip is not generated by the same model.
MAX_FORCE = 10.0

SENSING_MODES = {
    "full": (0, 1, 2, 3),      # (x, theta, p_x, p_theta)
    "positions": (0, 1),       # (x, theta) -- the q-only case, for later
}


# ---------------------------------------------------------------------------
# Container
# ---------------------------------------------------------------------------

@dataclass
class Trajectory:
    """One simulated run plus everything needed to reproduce or fit it."""

    t: np.ndarray            # (n+1,) times
    z: np.ndarray            # (n+1, 4) true states -- the thing to be recovered
    u: np.ndarray            # (n,) applied force, already clipped
    dW: np.ndarray           # (n,) noise increments actually used
    obs: np.ndarray          # (n+1, d) observations
    dt: float
    params: Params           # the TRUE parameters
    sensing: str
    obs_noise_std: np.ndarray  # (d,) per-channel std actually applied
    seed: Optional[int]

    @property
    def n_steps(self) -> int:
        return len(self.u)

    @property
    def obs_components(self) -> tuple:
        """Which state indices `obs` columns correspond to."""
        return SENSING_MODES[self.sensing]

    def true_obs(self) -> np.ndarray:
        """The noise-free observations -- the target a perfect fit would hit."""
        return self.z[:, self.obs_components]

    # -- persistence --------------------------------------------------------

    def save(self, path) -> None:
        np.savez(
            path,
            t=self.t, z=self.z, u=self.u, dW=self.dW, obs=self.obs,
            dt=self.dt, params=self.params.to_vector(),
            smooth_eps=self.params.smooth_eps,
            sensing=self.sensing, obs_noise_std=self.obs_noise_std,
            seed=-1 if self.seed is None else self.seed,
        )

    @classmethod
    def load(cls, path) -> "Trajectory":
        d = np.load(path, allow_pickle=False)
        seed = int(d["seed"])
        return cls(
            t=d["t"], z=d["z"], u=d["u"], dW=d["dW"], obs=d["obs"],
            dt=float(d["dt"]),
            params=Params.from_vector(d["params"], float(d["smooth_eps"])),
            sensing=str(d["sensing"]),
            obs_noise_std=d["obs_noise_std"],
            seed=None if seed < 0 else seed,
        )


# ---------------------------------------------------------------------------
# Initial conditions
# ---------------------------------------------------------------------------

def initial_state(params: Params, x=0.0, theta=0.0, xdot=0.0, thetadot=0.0) -> np.ndarray:
    """Build z0 = (x, theta, p_x, p_theta) from velocities via p = M(theta) qdot.

    Note that z0 then DEPENDS on the parameters.  For an inverse problem that
    matters: the adjoint derivation assumes dz0/dtheta = 0, which holds only if
    the initial MOMENTA are held fixed across parameter values.  Generate z0
    once at the true parameters and treat it as a fixed constant thereafter --
    do not re-derive it from velocities inside the objective.
    """
    px, pth = dyn.momenta_raw(theta, xdot, thetadot, params)
    return np.array([x, theta, px, pth], dtype=float)


# ---------------------------------------------------------------------------
# Input designs
# ---------------------------------------------------------------------------

def input_zero(n_steps: int) -> np.ndarray:
    """u = 0.  The pole falls under gravity; informative but the cart port is
    never excited, so nothing pins the u -> x channel."""
    return np.zeros(n_steps)


def input_sinusoid(n_steps: int, dt: float, amplitude=5.0, freq_hz=0.7, phase=0.0) -> np.ndarray:
    """A single tone.  Excites one frequency, so it identifies the transfer
    function at one point -- adequate for breaking the u = 0 degeneracy, weak
    for separating parameters that trade off across frequency."""
    t = np.arange(n_steps) * dt
    return amplitude * np.sin(2 * np.pi * freq_hz * t + phase)


def input_random_steps(n_steps: int, dt: float, rng, amplitude=5.0,
                       hold_seconds=0.2) -> np.ndarray:
    """Piecewise-constant uniform steps, each held `hold_seconds`.

    Preferred over a single sinusoid for identification: broadband input excites
    every mode, which is what makes the Fisher information full rank rather than
    merely nonzero.  `hold_seconds` trades bandwidth against excursion -- too
    short and the cart barely moves per block, too long and it leaves the region
    of interest.

    The hold is specified in SECONDS, not steps, deliberately: a design whose
    hold is a step count silently becomes a different physical signal when dt
    changes, which makes any convergence-in-dt study meaningless.
    """
    hold = max(int(round(hold_seconds / dt)), 1)
    n_blocks = int(np.ceil(n_steps / hold))
    blocks = rng.uniform(-amplitude, amplitude, size=n_blocks)
    return np.repeat(blocks, hold)[:n_steps]


# ---------------------------------------------------------------------------
# Rollout
# ---------------------------------------------------------------------------

def rollout(params: Params, z0, u, dt, rng=None, dW=None,
            max_force: Optional[float] = MAX_FORCE):
    """Integrate the stochastic-Heun map forward.  Returns (z, u_clipped, dW).

    Supply `dW` to re-simulate an existing noise path at different parameters --
    that is the call a gradient check makes.  Supply `rng` to draw a fresh one.
    """
    u = np.atleast_1d(np.asarray(u, dtype=float))
    n = len(u)
    if max_force is not None:
        u = np.clip(u, -max_force, max_force)

    if dW is None:
        if rng is None:
            raise ValueError("rollout needs either dW or rng")
        dW = np.sqrt(dt) * rng.standard_normal(n)
    else:
        dW = np.asarray(dW, dtype=float)
        if len(dW) != n:
            raise ValueError(f"dW has length {len(dW)}, expected {n} to match u")

    z = np.empty((n + 1, dyn.N_STATE))
    z[0] = np.asarray(z0, dtype=float)
    for k in range(n):
        z[k + 1] = dyn.heun_step(z[k], u[k], dW[k], dt, params)
    return z, u, dW


# ---------------------------------------------------------------------------
# Observation model
# ---------------------------------------------------------------------------

def observe(z, sensing="full", noise_std=0.0, rng=None) -> tuple:
    """Apply the observation model.  Returns (obs, noise_std_per_channel).

    `noise_std` is a scalar or one value per observed channel.  Per-channel is
    usually what you want: the state mixes radians, metres and momenta, so a
    single scalar is not a single physical noise level.  CartPoleEnv has no
    measurement noise of its own (unlike PendulumEnv) -- this is where it lives.
    """
    if sensing not in SENSING_MODES:
        raise ValueError(f"sensing must be one of {sorted(SENSING_MODES)}, got {sensing!r}")
    cols = SENSING_MODES[sensing]
    clean = np.asarray(z)[:, cols]

    std = np.broadcast_to(np.atleast_1d(np.asarray(noise_std, dtype=float)),
                          (len(cols),)).astype(float).copy()
    if np.any(std < 0):
        raise ValueError("noise_std must be non-negative")
    if np.all(std == 0):
        return clean.copy(), std
    if rng is None:
        raise ValueError("observe needs an rng when noise_std is nonzero")
    return clean + rng.standard_normal(clean.shape) * std, std


# ---------------------------------------------------------------------------
# One-call generation
# ---------------------------------------------------------------------------

def generate(params: Params, n_steps=1000, dt=0.02, z0=None, input_design="random_steps",
             sensing="full", obs_noise_std=0.0, seed=0, max_force=MAX_FORCE,
             input_kwargs=None) -> Trajectory:
    """Generate one labelled trajectory.

    `input_design` is "zero", "sinusoid", "random_steps", or an array of forces.
    One rng seeds both the wind and the measurement noise, so `seed` alone
    reproduces the dataset.
    """
    rng = np.random.default_rng(seed)
    kw = dict(input_kwargs or {})

    if isinstance(input_design, str):
        if input_design == "zero":
            u = input_zero(n_steps)
        elif input_design == "sinusoid":
            u = input_sinusoid(n_steps, dt, **kw)
        elif input_design == "random_steps":
            u = input_random_steps(n_steps, dt, rng, **kw)
        else:
            raise ValueError(f"unknown input_design {input_design!r}")
    else:
        u = np.asarray(input_design, dtype=float)
        n_steps = len(u)

    if z0 is None:
        # Slightly off upright, at rest.  Off-centre so sin(theta) != 0 and the
        # gravity term is live from step one; at rest so p0 carries no
        # information about the parameters (see `initial_state`).
        z0 = np.array([0.0, 0.05, 0.0, 0.0])

    z, u, dW = rollout(params, z0, u, dt, rng=rng, max_force=max_force)
    obs, std = observe(z, sensing=sensing, noise_std=obs_noise_std, rng=rng)

    return Trajectory(
        t=np.arange(len(z)) * dt, z=z, u=u, dW=dW, obs=obs, dt=dt,
        params=params, sensing=sensing, obs_noise_std=std, seed=seed,
    )


# ---------------------------------------------------------------------------
# Diagnostics
# ---------------------------------------------------------------------------

def hamiltonian_series(traj: Trajectory, params: Optional[Params] = None) -> np.ndarray:
    """H along the trajectory."""
    p = params or traj.params
    return np.array([dyn.hamiltonian(zk, p) for zk in traj.z])


def energy_drift(traj: Trajectory, params: Optional[Params] = None) -> dict:
    """How badly the integrator fails to conserve energy.

    Only interpretable when both ports are shut AND damping is off: u = 0,
    sigma = 0, R = 0.  Then Hdot = 0 exactly (grad H^T J grad H = 0), so every
    deviation is the integrator.  Stochastic Heun is not symplectic, so expect
    secular O(dt^2) drift accumulating with the horizon -- and note which way it
    goes, because an estimator will happily absorb energy LOSS into a fictitious
    damping term and report it as physics.

    That last point is why `interpretable` checks the damping parameters too: with
    R != 0 the energy SHOULD decay, at rate grad H^T R grad H, and the integrator
    error is no longer separable from real dissipation by this measure alone.  Run
    it once at zero damping to establish the integrator's floor, then require any
    recovered damping to produce decay well above that floor.
    """
    H = hamiltonian_series(traj, params)
    p_eff = params or traj.params
    ports_shut = bool(np.all(traj.u == 0.0)
                      and p_eff.sigma_gust == 0.0
                      and p_eff.sigma_turb == 0.0
                      and p_eff.b_cart == 0.0
                      and p_eff.b_base == 0.0
                      and p_eff.b_amp == 0.0)
    scale = max(abs(H[0]), float(np.ptp(H)), 1e-300)
    return {
        "H0": float(H[0]),
        "H_final": float(H[-1]),
        "drift_abs": float(H[-1] - H[0]),
        "max_dev_abs": float(np.max(np.abs(H - H[0]))),
        "max_dev_rel": float(np.max(np.abs(H - H[0])) / scale),
        "interpretable": ports_shut,
    }


def port_power_residual(traj: Trajectory) -> np.ndarray:
    """Check the Stratonovich energy balance dH = u xdot dt + sigma thetadot dW.

    Returns the per-step residual between the actual change in H and the two
    port terms, evaluated with the midpoint rule to match Heun's own second
    order.  This is the numerical statement of the pH claim: if the residual is
    O(dt^2) and not O(dt), the structure in `dynamics.J_PH` is the structure the
    simulated data actually has.
    """
    p = traj.params
    H = hamiltonian_series(traj)
    out = np.empty(traj.n_steps)
    for k in range(traj.n_steps):
        z0, z1 = traj.z[k], traj.z[k + 1]
        gH0, gH1 = dyn.grad_hamiltonian(z0, p), dyn.grad_hamiltonian(z1, p)
        # Midpoint (trapezoidal) port powers, matching the integrator's own rule.
        work = 0.5 * (gH0[2] + gH1[2]) * traj.u[k] * traj.dt
        wind = 0.5 * (dyn.diffusion(z0, p) * gH0[3]
                      + dyn.diffusion(z1, p) * gH1[3]) * traj.dW[k]
        out[k] = (H[k + 1] - H[k]) - work - wind
    return out
